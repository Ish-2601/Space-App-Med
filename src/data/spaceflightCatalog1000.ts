function routeFor(id: number, categoryId: number, type: CatalogItemType, body: CatalogBodySystem): string {
  if (categoryId === 10) return CATALOG_SOFTWARE_ROUTES[id];
  if (categoryId === 2) return "emergency";
  if (type === "Medication") return "medkit";
  if (categoryId === 8) return body === "wholeBody" ? "radiation" : "habitat";
  if (categoryId === 9) return "checklists";
  if (type === "Behavioral") return "body-brain";
  return "body-" + body;
}

