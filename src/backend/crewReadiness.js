const round = (value) => Math.round(value * 10) / 10;
export function workloadFor(state, pid) {
  const day = state.mission.day;
  const test = (state.tests[pid] || []).find(
    (t) => t.type === "tlx" && t.day === day,
  );
  const validTlx =
    test &&
    TLX_SCALES.every(
      (s) =>
        Number.isFinite(test.result[s.id]) &&
        test.result[s.id] >= 0 &&
        test.result[s.id] <= 100,
    );
  const sleep = rowFor(state, pid)?.sleep;
  const hasSleep = Number.isFinite(sleep) && sleep >= 0 && sleep <= 24;
  const debt = hasSleep ? Math.max(0, 8 - sleep) : null;
  const tlx = validTlx ? rawTlx(test.result) : null;
  const fatigue =
    tlx == null || debt == null
      ? null
      : Math.min(100, Math.round(tlx * 0.6 + Math.min(100, debt * 20) * 0.4));
  return {
    tlx,
    sleep: hasSleep ? sleep : null,
    sleepDebt: debt == null ? null : round(debt),
    fatigue,
    dimensions: validTlx ? test.result : null,
  };
}

export function evaReadiness(state, pid) {
  if (!state.crew.some((p) => p.id === pid))
    throw new Error("Choose a crew member.");
  const row = rowFor(state, pid) || {};
  const workload = workloadFor(state, pid);
  const checkin = state.checkins[pid]?.[state.mission.day];
  const score = healthScore(state, pid);
  const checks = {
    checkin: !!checkin && !checkin.auto,
    sleep: Number.isFinite(row.sleep) && row.sleep >= 6,
    oxygen: Number.isFinite(row.spo2) && row.spo2 >= 95,
    health: score >= 80,
    workload: workload.tlx != null && workload.tlx <= 65,
    environment:
      !activeEvent(state) && activeEmergencies(state, pid).length === 0,
  };
  return { eligible: Object.values(checks).every(Boolean), checks };
}

// The public snapshot explicitly enumerates public data. It never serializes the
// full store or reads sandbox logs. A change invalidates a previous transcript.
function publicSnapshot(state, pid) {
  const day = state.mission.day;
  const row = rowFor(state, pid) || {};
  return JSON.stringify({
    pid,
    day,
    environment: state.mission.environment,
    row,
    checkin: state.checkins[pid]?.[day] || null,
    diagnostics: (state.bodyDiagnostics?.[pid] || []).filter(
      (r) => r.day === day,
    ),
    symptoms: (state.symptomLog[pid] || []).filter((r) => r.day === day),
    tests: (state.tests[pid] || []).filter((r) => r.day === day),
    emergencyIds: activeEmergencies(state, pid).map((r) => r.id),
    event: activeEvent(state)?.id || null,
  });
}

