const Q = (P - 1n) / 2n,
  G = 4n;
export function modularPower(base, exponent, modulus = P) {
  let result = 1n;
  for (
    let e = exponent, b = base % modulus;
    e > 0n;
    e >>= 1n, b = (b * b) % modulus
  ) {
    if (e & 1n) result = (result * b) % modulus;
  }
  return result;
}
function cryptoApi() {
  if (!globalThis.crypto?.subtle || !globalThis.crypto?.getRandomValues)
    throw new Error(
      "Proof verification needs Web Crypto in a secure browser context.",
    );
  return globalThis.crypto;
}
const hex = (bytes) =>
  [...bytes].map((v) => v.toString(16).padStart(2, "0")).join("");
async function digest(text) {
  return hex(
    new Uint8Array(
      await cryptoApi().subtle.digest(
        "SHA-256",
        new TextEncoder().encode(text),
      ),
    ),
  );
}
function scalar() {
  let value;
  do {
    const bytes = cryptoApi().getRandomValues(new Uint8Array(256));
    bytes[0] &= 0x7f;
    value = BigInt("0x" + hex(bytes));
  } while (!value || value >= Q);
  return value;
}
async function statementFor(state, pid, nonce) {
  return {
    version: 2,
    purpose: "NASA Med local EVA readiness demo",
    pid,
    day: state.mission.day,
    fit: evaReadiness(state, pid).eligible,
    snapshot: await digest(publicSnapshot(state, pid)),
    nonce,
  };
}
let generatorPromise;
function blindingGenerator() {
  // Hash-to-subgroup with an independent domain: no participant chooses or
  // retains the discrete logarithm of H relative to G.
  generatorPromise ||= Promise.all(
    Array.from({ length: 8 }, (_, i) =>
      digest("NASA-MED-EVA-PEDERSEN-H-V2:" + i),
    ),
  ).then((pieces) => {
    const h = modularPower(BigInt("0x" + pieces.join("")) % P, 2n);
    if (h <= 1n || h === G)
      throw new Error("Unable to derive the proof generator.");
    return h;
  });
  return generatorPromise;
}
async function challenge(statement, h, commitments, announcements) {
  return BigInt(
    "0x" +
      (await digest(
        JSON.stringify([
          "NASA-MED-EVA-ALL-TRUE-V2",
          G.toString(16),
          h.toString(16),
          commitments,
          announcements,
          statement,
        ]),
      )),
  );
}
export async function createEvaProof(state, pid) {
  const nonce = hex(cryptoApi().getRandomValues(new Uint8Array(16)));
  const statement = await statementFor(state, pid, nonce);
  if (!statement.fit)
    throw new Error(
      "Complete or review the public readiness checks before generating a Fit-for-EVA demo proof.",
    );
  const h = await blindingGenerator();
  const bits = Object.values(evaReadiness(state, pid).checks);
  if (!bits.every(Boolean))
    throw new Error("Public readiness changed. Review the checks first.");
  const openings = bits.map(() => scalar()),
    nonces = bits.map(() => scalar());
  const commitments = bits.map((bit, i) =>
    (
      (modularPower(G, bit ? 1n : 0n) * modularPower(h, openings[i])) %
      P
    ).toString(16),
  );
  const announcements = nonces.map((value) =>
    modularPower(h, value).toString(16),
  );
  const c = await challenge(statement, h, commitments, announcements);
  const responses = openings.map((value, i) =>
    ((nonces[i] + c * value) % Q).toString(16),
  );
  return {
    statement,
    commitments,
    announcements,
    responses,
    createdAt: Date.now(),
  };
}
export async function verifyEvaProof(state, pid, proof) {
  try {
    if (
      !proof ||
      !proof.statement?.fit ||
      proof.statement.pid !== pid ||
      proof.statement.day !== state.mission.day ||
      !/^[a-f0-9]{32}$/.test(proof.statement.nonce)
    )
      return false;
    const statement = await statementFor(state, pid, proof.statement.nonce);
    if (
      !statement.fit ||
      JSON.stringify(statement) !== JSON.stringify(proof.statement)
    )
      return false;
    if (
      ![proof.commitments, proof.announcements, proof.responses].every(
        (list) =>
          Array.isArray(list) &&
          list.length === 6 &&
          list.every(
            (v) => typeof v === "string" && /^[a-f0-9]{1,512}$/.test(v),
          ),
      )
    )
      return false;
    const h = await blindingGenerator();
    const c = await challenge(
      proof.statement,
      h,
      proof.commitments,
      proof.announcements,
    );
    const inverseG = modularPower(G, P - 2n);
    // Each C = G^bit H^opening must prove knowledge of an opening for bit=1:
    // H^response = announcement * (C/G)^challenge. A zero bit cannot satisfy
    // this without knowing log_H(G). The same challenge binds all six proofs.
    for (let i = 0; i < 6; i++) {
      const commitment = BigInt("0x" + proof.commitments[i]);
      const announcement = BigInt("0x" + proof.announcements[i]);
      const response = BigInt("0x" + proof.responses[i]);
      if (
        commitment <= 1n ||
        commitment >= P - 1n ||
        announcement <= 1n ||
        announcement >= P - 1n ||
        response >= Q ||
        modularPower(commitment, Q) !== 1n ||
        modularPower(announcement, Q) !== 1n
      )
        return false;
      if (
        modularPower(h, response) !==
        (announcement * modularPower((commitment * inverseG) % P, c)) % P
      )
        return false;
    }
    return true;
  } catch {
    return false;
  }
}
export async function generateAndSaveEvaProof(pid) {
  const proof = await createEvaProof(getState(), pid);
  if (!(await verifyEvaProof(getState(), pid, proof)))
    throw new Error(
      "Readiness changed while generating the proof. Review and try again.",
    );
  update((state) => {
    state.evaProofs ||= {};
    state.evaProofs[pid] = proof;
  });
  return proof;
}
